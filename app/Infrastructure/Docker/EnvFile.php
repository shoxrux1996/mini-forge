<?php

declare(strict_types=1);

namespace App\Infrastructure\Docker;

use App\Models\SiteEnvironmentVariable;
use InvalidArgumentException;

final class EnvFile
{
    /**
     * A Laravel .env file. Every value is double-quoted with \, " and $
     * escaped, which phpdotenv reads back unchanged (newlines included).
     *
     * @param  array<string, ?string>  $variables
     */
    public static function render(array $variables): string
    {
        $lines = ['# Generated by Mini Forge. Edit environment variables in Mini Forge, not here.'];

        foreach ($variables as $key => $value) {
            if (preg_match(SiteEnvironmentVariable::KEY_PATTERN, $key) !== 1) {
                throw new InvalidArgumentException("Invalid environment variable name [{$key}].");
            }

            $lines[] = $key.'="'.str_replace(['\\', '"', '$'], ['\\\\', '\\"', '\\$'], (string) $value).'"';
        }

        return implode("\n", $lines)."\n";
    }
}
